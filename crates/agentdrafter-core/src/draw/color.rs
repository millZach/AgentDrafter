//! AutoCAD's colours: the colour index every layer names, and the colour
//! each index plots in.

use serde::{Deserialize, Serialize};

/// An AutoCAD colour index, 1 to 255, as a layer names it.
///
/// It is written as the number in JSON.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(transparent)]
pub struct Color(pub u8);

/// The colour index that draws white on a dark screen and black on paper.
pub const WHITE: Color = Color(7);

impl Color {
    /// The red, green and blue the index stands for. Index 7 is white here:
    /// [`Color::on_paper`] says what it plots in.
    pub fn rgb(self) -> [u8; 3] {
        PALETTE[usize::from(self.0)]
    }

    /// The red, green and blue the index plots in on white paper, as
    /// AutoCAD plots it: index 7 plots black, and every other index plots
    /// in its own colour.
    pub fn on_paper(self) -> [u8; 3] {
        if self == WHITE {
            [0, 0, 0]
        } else {
            self.rgb()
        }
    }
}

