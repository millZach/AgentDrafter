#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn colours_plot_as_autocad_plots_them() {
        assert_eq!(Color(1).on_paper(), [255, 0, 0]);
        assert_eq!(Color(2).on_paper(), [255, 255, 0]);
        assert_eq!(Color(3).on_paper(), [0, 255, 0]);
        assert_eq!(Color(4).on_paper(), [0, 255, 255]);
        assert_eq!(Color(5).on_paper(), [0, 0, 255]);
        assert_eq!(Color(6).on_paper(), [255, 0, 255]);
        assert_eq!(Color(8).on_paper(), [128, 128, 128]);
        assert_eq!(Color(9).on_paper(), [220, 220, 220]);
        assert_eq!(Color(11).on_paper(), [255, 127, 127]);
        assert_eq!(Color(250).on_paper(), [84, 84, 84]);
    }

    #[test]
    fn white_plots_black_on_paper() {
        assert_eq!(WHITE.rgb(), [255, 255, 255]);
        assert_eq!(WHITE.on_paper(), [0, 0, 0]);
    }
}
